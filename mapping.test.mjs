import {strict as assert} from 'node:assert';
import {parsePacket,mapInputs} from './mapping.js';
const analog={id:'a',field:'distance',type:'analog',low:100,high:250,margin:10,below:'4',middle:'',above:'5'};
const digital={id:'d',field:'buttonA',type:'digital',on:'0'};
const samples=(distance,buttonA)=>({distance:{value:distance,time:1000},buttonA:{value:buttonA,time:1000}});
const run=(d,b,prev={})=>mapInputs([analog,digital],samples(d,b),prev,1000);
assert.deepEqual(parsePacket('{"distance":150,"buttonA":true}'),{distance:150,buttonA:true});
for(const line of ['null','boot','[]','{"buttonA":"ON"}'])assert.equal(parsePacket(line),null);
assert.deepEqual(run(50,true).keys,[4,0]);
assert.deepEqual(run(170,false).keys,[]);
assert.deepEqual(run(250,1).keys,[5,0]);
assert.deepEqual(run(105,0,{a:'below'}).keys,[4]);
assert.deepEqual(run(110,0,{a:'below'}).keys,[]);
assert.deepEqual(run(245,0,{a:'above'}).keys,[5]);
assert.deepEqual(run(239,0,{a:'above'}).keys,[]);
assert.deepEqual(run(8190,2).keys,[]);
assert.deepEqual(mapInputs([analog,digital],{distance:{value:50,time:2001},buttonA:{value:1,time:1000}},{},2001).keys,[4]);
const shared=[{...digital,on:'0'},{...digital,id:'e',field:'switch2',on:'0'}];
assert.deepEqual(mapInputs(shared,{buttonA:{value:0,time:1000},switch2:{value:1,time:1000}},{},1000).keys,[0]);
assert.deepEqual(mapInputs(shared,{}, {},2001).keys,[]);
const bad=mapInputs([{...analog,low:300}],samples(100,0),{},1000);
assert.deepEqual(bad.keys,[]);assert.deepEqual(bad.errors,['a']);
assert.deepEqual(mapInputs([{...analog,field:'tilt',low:-10,high:10,margin:0,below:'2',above:'3'}],{tilt:{value:-12,time:1000}},{},1000).keys,[2]);
console.log('Mapping checks passed: analog ranges, hysteresis, digital ON/OFF, simultaneous inputs, shared buttons, per-channel timeout and invalid data.');

// Keep the input until 49 ms, then clear its button and value at 50 ms.
const fresh = mapInputs([analog,digital],samples(50,1),{},1049);
assert.deepEqual(fresh.keys,[4,0]);
const expired = mapInputs([analog,digital],samples(50,1),{},1050);
assert.deepEqual(expired.keys,[]);
assert.equal(expired.values.a,'データ待ち');
assert.equal(expired.values.d,'データ待ち');
console.log('50 ms timeout boundary checks passed.');
